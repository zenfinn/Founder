export function resolveSeedKey(group) {
  const slug = String(group?.slug ?? "").toLowerCase();
  if (GROUP_SEED_KEYS[slug]) return GROUP_SEED_KEYS[slug];

  const category = String(group?.category ?? group?.name ?? "").toLowerCase();

  if (category.includes("founder pro")) return "founder-pro";
  if (category.includes("amazon") && category.includes("fba")) return "amazon-fba";
  if (category.includes("fba")) return "amazon-fba";
  if (category.includes("memecoin")) return "memecoin-trading";
  if (category.includes("drop")) return "dropshipping";
  if (category.includes("resell")) return "reselling";
  if (category.includes("tiktok") && category.includes("shop")) return "tiktok-shop";
  if (category.includes("ki")) return "ki-creator";
  if (category.includes("youtube")) return "youtube-automation";
  if (category.includes("tiktok")) return "tiktok-creator";
  if (category.includes("digital business")) return "digital-business";
  if (category.includes("commerce")) return "e-commerce";
  if (category.includes("trad") || category.includes("crypto")) return "trading";

  return DEFAULT_SEED_KEY;
}
